/**
 * Painted units with orthographic views. Facing runs 0 = left, 2 = up, 4 = right,
 * 6 = down, so the side view serves both left and right by mirroring, and the
 * diagonals round to whichever of the three reads best.
 */
const UNIT_VIEWS: Record<string, { front: string; side: string; back: string }> = {
  footman: { front: footmanFront, side: footmanSide, back: footmanBack },
  archer: { front: archerFront, side: archerSide, back: archerBack },
  // The ballista is a machine, not a man: one three-quarter view serves every
  // facing, mirrored for the left half of the compass. Cutting a front and back
  // view would mean redrawing the carriage, and a siege engine that always
  // presents its flank reads fine at this size.
  ballista: { front: ballistaSrc, side: ballistaSrc, back: ballistaSrc },
  // The royal line borrows the footman's plate until it has art of its own. A
  // crown is drawn over it by the renderer, so a King is never mistaken for a
  // swordsman even while they share a sprite.
  king: { front: footmanFront, side: footmanSide, back: footmanBack },
  prince: { front: footmanFront, side: footmanSide, back: footmanBack },
  // The cannon sheet came with real orthographic views, so it gets three
  // genuine ones rather than a flank repeated three times.
  cannon: { front: cannonFront, side: cannonSide, back: cannonBack },
};

/**
 * Height of a painted unit as a multiple of the tile size. Men are taller than
 * they are wide so the default suits them; the ballista is the other way round
 * and would be three tiles across if it used the same rule.
 */
export const UNIT_VIEW_HEIGHT: Record<string, number> = { ballista: 1.3, cannon: 0.95 };

for (const v of Object.values(UNIT_VIEWS)) for (const src of Object.values(v)) load(src);

/** The view to draw for a facing, and whether to mirror it. */
export function unitViewSprite(def: string, facing: number, color: string): { img: HTMLCanvasElement; mirror: boolean } | null {
  const views = UNIT_VIEWS[def];
  if (!views) return null;
  const src = facing === 6 ? views.front : facing === 2 ? views.back : views.side;
  const mirror = facing === 7 || facing === 0 || facing === 1;
  const key = src + "|" + color;
  const cached = tinted.get(key);
  if (cached) return { img: cached, mirror };
  const img = load(src);
  if (!img.complete || img.naturalWidth === 0) return null;
  const c = tint(img, color);
  tinted.set(key, c);
  return { img: c, mirror };
}

