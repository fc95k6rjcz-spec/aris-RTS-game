/**
 * Forest trees. Ten painted variants, picked per tile so a wood is a mixed stand
 * rather than one tree stamped in a grid.
 *
 * The weights keep the two conifers common — they read as "forest" at a glance —
 * and make the blossom, maple and the willow with its pond occasional, because a
 * map covered in cherry blossom stops looking like terrain and starts looking
 * like decoration. The willow is rarest of all: it carries water in its base,
 * which is a lovely accident once and a wrong one in a dense wood.
 */
const TREE_SET: string[] = [tree1, tree2, tree3, tree4, tree5, tree6, tree7, tree8, tree9, tree10];
// Greens and conifers dominate; the birch, blossom, maple and willow are rare.
// At even weights a treeline came out looking like an autumn display rather than
// a forest — a few coloured trees read as variety, many read as decoration.
const TREE_WEIGHTS = [7, 7, 6, 6, 1, 1, 1, 1, 7, 6];
const TREE_TOTAL = TREE_WEIGHTS.reduce((a, b) => a + b, 0);

/** Pick a variant for a tile from a 0..1 value; stable for a given tile. */
export function treeVariant(r: number): number {
  let acc = Math.floor(r * TREE_TOTAL);
  for (let i = 0; i < TREE_WEIGHTS.length; i++) {
    acc -= TREE_WEIGHTS[i]!;
    if (acc < 0) return i;
  }
  return 0;
}

for (const t of TREE_SET) load(t);

export function treeSprite(variant = 0): HTMLImageElement | null {
  const img = load(TREE_SET[variant % TREE_SET.length]!);
  return img.complete && img.naturalWidth > 0 ? img : null;
}

